"""Default-path regression: build_targets with default heatmap_divisor / heatmap_shape must reproduce, bit for bit,
the arrays stored in tests/data/targets_default_ref.npz, generated by the pre-P3a implementation (commit dd3f874)."""
from pathlib import Path

import numpy as np
import pytest

from dccnet.datasets.targets import build_targets

IMG, MAXOBJ = 64, 16
# touching same-class pair (0,1), a third class-0 cell, a border-clipped class-0 cell, a class-1 cell right next
# to class 0, a lone class-1 cell far away; class 2 has zero cells
CIRCLES = np.array([
    [20.3, 20.6, 8.0],
    [36.1, 20.6, 8.0],
    [40.7, 45.2, 6.5],
    [62.4, 2.9, 4.0],
    [28.2, 31.0, 5.0],
    [9.5, 54.8, 3.3],
], dtype=np.float64)
LABELS = np.array([0, 0, 0, 0, 1, 1], dtype=np.int64)
VALID = np.array([True, True, True, False, True, True])
CASES = [("radius", 1), ("radius", 2), ("adaptive", 1), ("adaptive", 2)]
REF = Path(__file__).resolve().parent / "data" / "targets_default_ref.npz"


@pytest.mark.parametrize("sigma, stride", CASES)
def test_default_targets_bit_identical_to_stored_reference(sigma, stride):
    ref = np.load(REF)
    t = build_targets(CIRCLES, LABELS, VALID, img_size=IMG, stride=stride, num_classes=3, max_objs=MAXOBJ,
                      heatmap_sigma=sigma)
    keys = {k[len(f"{sigma}_s{stride}_"):] for k in ref.files if k.startswith(f"{sigma}_s{stride}_")}
    assert keys == set(t)
    for k, v in t.items():
        r = ref[f"{sigma}_s{stride}_{k}"]
        assert v.numpy().dtype == r.dtype and np.array_equal(v.numpy(), r), k
    assert np.abs(t["heatmap"].numpy()[2]).sum() == 0  # class with zero cells
